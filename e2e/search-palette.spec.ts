import { expect, test } from '@playwright/test'

test('search palette navigates results and closes with a nonempty query', async ({ page }) => {
  await page.goto('/en/government')
  await expect(page.locator('.header-search')).toBeVisible()
  await page.keyboard.press('Control+k')
  const search = page.getByRole('combobox', { name: 'Search records, topics and sources' })
  await expect(search).toBeFocused()
  await search.fill('services')
  await expect(page.getByRole('option').first().locator('a')).toHaveAttribute('href', '/en/services')
  await expect(page.getByRole('option').first()).toContainText('Services')
  await search.fill('cavinti')
  const options = page.getByRole('option')
  await expect(options.first()).toBeVisible()
  await page.keyboard.press('ArrowDown')
  await expect(options.nth(1)).toHaveAttribute('aria-selected', 'true')
  const destination = await options.nth(1).locator('a').getAttribute('href')
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(new RegExp(`${destination}$`))
  await expect(page.locator('.header-search')).toBeVisible()
  await page.keyboard.press('Control+k')
  await search.fill('cavinti')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeHidden()
})
