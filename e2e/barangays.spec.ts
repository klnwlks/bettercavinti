import { expect, test } from '@playwright/test'

test('year selection preserves distinct source names and missing population', async ({ page }) => {
  await page.goto('/en/government/barangays')
  await page.getByLabel('Find a barangay').fill('Mahipon')
  const entries = page.locator('.barangay-bars > li')
  await expect(entries).toHaveCount(2)
  const populationEntry = entries.filter({ has: page.getByText('Mahipon', { exact: true }) })
  const unmatchedEntry = entries.filter({ has: page.getByText('Mahipon-Lumot', { exact: true }) })
  await expect(populationEntry).toContainText('2,475')
  await expect(unmatchedEntry.locator('.barangay-bar-track')).toHaveCount(0)
  await expect(unmatchedEntry).not.toContainText('2,475')
  await page.getByLabel('Reference period').selectOption('2015')
  await expect(populationEntry).toContainText('2,097')
  await unmatchedEntry.getByRole('link').click()
  await expect(page.locator('h1')).toHaveText('Mahipon-Lumot')
  await expect(page.locator('main')).toContainText('No published population for this exact name')
  await expect(page.locator('.barangay-bars')).toHaveCount(0)
  await page.getByRole('link', { name: 'Filipino', exact: true }).click()
  await expect(page.locator('h1')).toHaveText('Mahipon-Lumot')
  await expect(page.locator('main')).toContainText('Walang inilathalang populasyon para sa eksaktong pangalang ito')
})

test('population sorting and empty search remain usable', async ({ page }) => {
  await page.goto('/en/government/barangays')
  await page.getByLabel('Sort by').selectOption('population')
  const first = page.locator('.barangay-bars > li').first()
  await expect(first).toContainText('Poblacion')
  await expect(first).toContainText('6,696')
  await page.getByLabel('Reference period').selectOption('2015')
  await expect(first).toContainText('6,358')
  await page.getByLabel('Find a barangay').fill('no-such-barangay')
  await expect(page.locator('.barangay-bars > li')).toHaveCount(0)
  await page.getByLabel('Find a barangay').fill('Anglas')
  await expect(first).toContainText('331')
  await first.getByRole('link').click()
  await expect(page.locator('h1')).toHaveText('Anglas')
  await expect(page.locator('.barangay-bars > li').first()).toContainText('331')
  await expect(page.locator('.barangay-bars > li').last()).toContainText('427')
})

test('unknown barangay IDs never display another name’s population', async ({ page }) => {
  await page.goto('/en/government/barangays/barangay:not-a-record')
  await expect(page.locator('h1')).toHaveText('Page or record not found')
  await expect(page.locator('.barangay-bars')).toHaveCount(0)
})
